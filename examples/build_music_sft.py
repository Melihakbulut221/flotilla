"""Build the music SFT set (see flotilla/rl/music_sft.py and docs/music_sft.md).

    # 1. fetch the Nottingham Music Database, cleaned ABC (GPL-3.0), pinned commit, ~0.5 MB
    python examples/build_music_sft.py --download

    # 2. build train/val JSON Lines in data/music_sft/
    python examples/build_music_sft.py --nottingham data/raw/nottingham --out data/music_sft

The output is chat-format JSON Lines, one example per line:
``messages`` (user prompt, assistant ABC), plus ``constraints``, ``source``,
``license``, ``lang``, ``group`` and ``reward``. TRL's SFTTrainer reads the
``messages`` column directly.

License: examples with source "nottingham" are derived from GPL-3.0 data and
are GPL-3.0; "synthetic" examples are generated by flotilla (Apache-2.0).
Keep the generated files out of the Apache-licensed repository, or publish
them separately under GPL-3.0.
"""

import argparse
import json
import sys
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from flotilla.rl.music_sft import build_dataset, write_jsonl  # noqa: E402

REPO = "jukedeck/nottingham-dataset"
COMMIT = "0992bb6cd864f6d4b90d6663e08c0ef53ffaa08f"   # 2017-03-03, the last commit
FILES = ["ashover", "hpps", "jigs", "morris", "playford", "reelsa-c", "reelsd-g", "reelsh-l", "reelsm-q",
         "reelsr-t", "reelsu-z", "slip", "waltzes", "xmas"]


def download(dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    base = f"https://raw.githubusercontent.com/{REPO}/{COMMIT}"
    for name in [f"ABC_cleaned/{f}.abc" for f in FILES] + ["LICENSE.md", "README.md"]:
        target = dest / Path(name).name
        with urllib.request.urlopen(f"{base}/{name}", timeout=60) as r:
            target.write_bytes(r.read())
        print(f"  {target}  {target.stat().st_size} bytes", file=sys.stderr)
    (dest / "SOURCE.txt").write_text(f"https://github.com/{REPO}/tree/{COMMIT}\nLicense: GPL-3.0 (LICENSE.md)\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--download", action="store_true", help="fetch the Nottingham ABC files first")
    ap.add_argument("--nottingham", default="data/raw/nottingham")
    ap.add_argument("--out", default="data/music_sft")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--transpositions", type=int, default=2, help="extra keys per tune")
    ap.add_argument("--synthetic-fraction", type=float, default=0.15)
    ap.add_argument("--val-fraction", type=float, default=0.05)
    args = ap.parse_args()

    src = Path(args.nottingham)
    if args.download:
        print(f"downloading {REPO}@{COMMIT[:7]} -> {src}", file=sys.stderr)
        download(src)
    if not any(src.glob("*.abc")):
        sys.exit(f"no .abc files in {src}; run with --download first")
    train, val, stats = build_dataset(src, seed=args.seed, transpositions=args.transpositions,
                                      synthetic_fraction=args.synthetic_fraction, val_fraction=args.val_fraction)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    write_jsonl(train, out / "train.jsonl")
    write_jsonl(val, out / "val.jsonl")
    stats["seed"], stats["source_commit"] = args.seed, f"{REPO}@{COMMIT}"
    (out / "stats.json").write_text(json.dumps(stats, indent=2, ensure_ascii=False))
    (out / "LICENSE.txt").write_text(
        "Examples with source \"nottingham\" are derived from the Nottingham Music Database as cleaned by\n"
        f"{REPO} ({COMMIT}), licensed GPL-3.0; those examples are GPL-3.0.\n"
        "Examples with source \"synthetic\" are generated by flotilla and are Apache-2.0.\n")
    print(json.dumps(stats, indent=2, ensure_ascii=False))
    print(f"wrote {out}/train.jsonl ({len(train)}), {out}/val.jsonl ({len(val)})", file=sys.stderr)


if __name__ == "__main__":
    main()
